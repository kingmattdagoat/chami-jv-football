export function textWidth(text: string, scale = 1) {
  return text.length * 4 * scale - scale
}

export function drawText(
  ctx: CanvasRenderingContext2D,
  text: string,
  x: number,
  y: number,
  color: string,
  scale = 1,
  shadow: string | null = '#000',
) {
  const up = text.toUpperCase()
  const draw = (ox: number, oy: number, c: string) => {
    ctx.fillStyle = c
    for (let i = 0; i < up.length; i++) {
      const g = G[up[i]] ?? G['?']
      for (let k = 0; k < 15; k++) {
        if (g[k] === '1') ctx.fillRect(Math.round(x + ox + (i * 4 + (k % 3)) * scale), Math.round(y + oy + Math.floor(k / 3) * scale), scale, scale)
      }
    }
  }
  if (shadow) draw(scale, scale, shadow)
  draw(0, 0, color)
}
